export const TRANSLATIONS: Record<SupportedLanguage, TranslationDict> = {
  en: EN,
  hi: HI,
  mr: MR,
};

export function translateKey(lang: SupportedLanguage, key: string, fallback?: string): string {
  return TRANSLATIONS[lang]?.[key] || EN[key] || fallback || key;
}

export function getLocalizedField<K extends keyof LocalizedSiteCopy>(
  settings: CompanySettings | null | undefined,
  lang: SupportedLanguage,
  field: K,
  fallbackValue: string
): string {
  const localized = settings?.localizedContent?.[lang]?.[field];
  if (typeof localized === 'string' && localized.trim()) return localized;
  const direct = (settings as Record<string, any> | null | undefined)?.[field];
  if (typeof direct === 'string' && direct.trim()) return direct;
  return fallbackValue;
}
